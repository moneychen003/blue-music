const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { createRequire } = require('node:module')
const root = path.join(__dirname, '..')
const desktopRequire = createRequire(path.join(root, 'packages/desktop/package.json'))
const builderRequire = createRequire(desktopRequire.resolve('electron-builder'))
const appRequire = createRequire(builderRequire.resolve('app-builder-lib'))
const util = appRequire('builder-util')
require('../packages/desktop/build-config/builder-compat.cjs')
const config = fs.readFileSync(path.join(root, 'packages/desktop/build-config/build-pack.cjs'), 'utf8')
const compile = fs.readFileSync(path.join(root, 'packages/shared/scripts/pack-desktop.ts'), 'utf8')
;(async () => {
  const output = await util.spawnAndWriteWithOutput(process.execPath, ['-e', 'process.stdin.on("data", x=>{process.stdout.write(x);process.stderr.write("diagnostic")})'], 'same-input')
  assert.deepEqual(output, { stdout: 'same-input', stderr: 'diagnostic' })
  await assert.rejects(util.spawnAndWriteWithOutput(process.execPath, ['-e', 'process.stdin.resume();process.stdin.on("end",()=>{process.stderr.write("intentional failure");process.exit(7)})'], 'same-input'), /intentional failure/)
  assert.equal(desktopRequire('./package.json').version, '1.2.1')
  assert.match(config, /perMachine: false/)
  assert.match(config, /allowElevation: false/)
  assert.match(config, /runAfterFinish: false/)
  assert.match(config, /publish: null/)
  assert.match(config, /bundled-extensions\/jide-open-music/)
  assert.match(config, /bundled-extensions\/gdstudio/)
  assert.match(compile, /JIDE_TARGET_PLATFORM/)
  assert.match(compile, /delete process.env\[flag\]/)
  console.log('PASS Windows target-platform selection, version 1.2.1, per-user installer, no auto-run/publish, bundled open source, NSIS stdout/stderr and nonzero propagation')
})().catch(error => { console.error(error); process.exitCode = 1 })
